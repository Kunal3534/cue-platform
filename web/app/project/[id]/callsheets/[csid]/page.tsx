"use client";
import { useParams } from "next/navigation";
import { useQuery } from "@tanstack/react-query";
import { useState } from "react";
import Link from "next/link";
import {
  getCallSheetPdf,
  listCallSheets,
  getMainSchedule,
  sendCallSheet,
} from "@/lib/api";
import { useProjectStore } from "@/stores/project";

export default function CallSheetDetailPage() {
  const params = useParams();
  const projectId = params.id as string;
  const callSheetId = params.csid as string;
  const scenarioId = useProjectStore((s) => s.activeScenarioId) ?? undefined;

  const { data: sheets } = useQuery({
    queryKey: ["callsheets", projectId],
    queryFn: () => listCallSheets(projectId),
  });

  const { data: main } = useQuery({
    queryKey: ["view", projectId, "main_schedule", scenarioId],
    queryFn: () => getMainSchedule(projectId, scenarioId),
  });

  const { data: pdf, isLoading, error } = useQuery({
    queryKey: ["callsheet-pdf", projectId, callSheetId],
    queryFn: () => getCallSheetPdf(projectId, callSheetId),
    retry: false,
  });

  const sheet = sheets?.find((cs) => cs.id === callSheetId);
  const day = main?.days.find((d) => d.day_id === sheet?.day_id);

  const [sending, setSending] = useState(false);
  const [sendError, setSendError] = useState<string | null>(null);
  const [sendOk, setSendOk] = useState(false);

  const handleSend = async () => {
    const email = window.prompt("Recipient email:");
    if (!email) return;
    setSending(true);
    setSendError(null);
    try {
      await sendCallSheet(projectId, callSheetId, [{ email }]);
      setSendOk(true);
    } catch (e) {
      setSendError(e instanceof Error ? e.message : "Send failed");
    } finally {
      setSending(false);
    }
  };

  const dateLabel = day
    ? new Date(day.date).toLocaleDateString("en-IN", {
        weekday: "long",
        day: "numeric",
        month: "long",
        year: "numeric",
      })
    : null;

  return (
    <div style={{ paddingTop: "32px" }}>
      <div className="row" style={{ marginBottom: "24px" }}>
        <div>
          <div className="meta meta--red">Call Sheet</div>
          <h2 className="display--sm" style={{ marginTop: "8px" }}>
            {dateLabel ?? `#${callSheetId.slice(0, 8)}`}
          </h2>
          {sheet && (
            <div className="mono-xs" style={{ marginTop: "6px", color: "var(--slate-50)" }}>
              v{sheet.version} · {sheet.status}
              {sheet.sent_at ? " · sent" : ""}
            </div>
          )}
        </div>
        <div style={{ display: "flex", gap: "12px" }}>
          {pdf?.url && (
            <a
              href={pdf.url}
              target="_blank"
              rel="noopener noreferrer"
              className="btn btn--primary btn--sm"
            >
              Download PDF →
            </a>
          )}
          <button
            className="btn btn--day btn--sm"
            onClick={handleSend}
            disabled={sending}
          >
            {sending ? "Sending…" : "Send →"}
          </button>
          <Link
            href={`/project/${projectId}/callsheets`}
            className="btn btn--ghost btn--sm"
          >
            ← All sheets
          </Link>
        </div>
      </div>

      {sendError && (
        <p className="mono-xs" style={{ color: "var(--cue-red)", marginBottom: "12px" }}>
          {sendError}
        </p>
      )}
      {sendOk && (
        <p className="mono-xs" style={{ color: "var(--slate-70)", marginBottom: "12px" }}>
          Queued for delivery.
        </p>
      )}

      {isLoading && <p className="voice">Loading call sheet…</p>}

      {error && (
        <div className="empty">
          <p className="voice" style={{ fontSize: "15px" }}>
            Call sheet PDF not available yet, or failed to load.
          </p>
        </div>
      )}

      {pdf?.url && (
        <div className="cs">
          <div className="cs__hdr">
            <div className="cs__hdr-title">Production Call Sheet</div>
            {dateLabel && <div className="cs__hdr-sub">{dateLabel}</div>}
            <div className="cs__hdr-meta">Generated by Cue v1</div>
          </div>
          <div style={{ marginTop: "32px", textAlign: "center" }}>
            <p className="voice" style={{ fontSize: "15px" }}>
              Full PDF available above.{" "}
              <a
                href={pdf.url}
                target="_blank"
                rel="noopener noreferrer"
                style={{ color: "var(--cue-red)", textDecoration: "underline" }}
              >
                Open PDF →
              </a>
            </p>
          </div>
        </div>
      )}
    </div>
  );
}
