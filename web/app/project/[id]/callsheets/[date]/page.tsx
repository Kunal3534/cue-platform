"use client";
import { useParams } from "next/navigation";
import { useQuery } from "@tanstack/react-query";
import { getCallSheetUrl } from "@/lib/api";
import Link from "next/link";

export default function CallSheetDetailPage() {
  const params = useParams();
  const projectId = params.id as string;
  const date = params.date as string;

  const { data, isLoading, error } = useQuery({
    queryKey: ["callsheet-url", projectId, date],
    queryFn: () => getCallSheetUrl(projectId, date),
  });

  return (
    <div style={{ paddingTop: "32px" }}>
      <div className="row" style={{ marginBottom: "24px" }}>
        <div>
          <div className="meta meta--red">Call Sheet</div>
          <h2 className="display--sm" style={{ marginTop: "8px" }}>
            {new Date(date).toLocaleDateString("en-IN", {
              weekday: "long",
              day: "numeric",
              month: "long",
              year: "numeric",
            })}
          </h2>
        </div>
        <div style={{ display: "flex", gap: "12px" }}>
          {data?.url && (
            <a
              href={data.url}
              target="_blank"
              rel="noopener noreferrer"
              className="btn btn--primary btn--sm"
            >
              Download PDF →
            </a>
          )}
          <Link
            href={`/project/${projectId}/callsheets`}
            className="btn btn--ghost btn--sm"
          >
            ← All sheets
          </Link>
        </div>
      </div>

      {isLoading && <p className="voice">Loading call sheet…</p>}

      {error && (
        <div className="empty">
          <p className="voice" style={{ fontSize: "15px" }}>
            Call sheet not generated yet, or failed to load.
          </p>
        </div>
      )}

      {data?.url && (
        <div className="cs">
          <div className="cs__hdr">
            <div className="cs__hdr-title">Production Call Sheet</div>
            <div className="cs__hdr-sub">
              {new Date(date).toLocaleDateString("en-IN", {
                weekday: "long",
                day: "numeric",
                month: "long",
                year: "numeric",
              })}
            </div>
            <div className="cs__hdr-meta">Generated by Cue v1</div>
          </div>

          <div style={{ marginTop: "32px", textAlign: "center" }}>
            <p className="voice" style={{ fontSize: "15px" }}>
              Full PDF available above.{" "}
              <a
                href={data.url}
                target="_blank"
                rel="noopener noreferrer"
                style={{ color: "var(--cue-red)", textDecoration: "underline" }}
              >
                Open PDF →
              </a>
            </p>
          </div>
        </div>
      )}
    </div>
  );
}
